//! Z10 tests:
//! 1. snapshot of the generated tests/swarm.rs per fixture
//! 2. init without --yes leaves src/ byte-identical
//! 3. full init && run flow on fixture (1) writes report.json
//!
//! Fixtures live as standalone workspaces (workspace-excluded).

use std::path::{Path, PathBuf};
use std::process::Command;

fn cli_bin() -> PathBuf {
    PathBuf::from(env!("CARGO_BIN_EXE_cargo-swarm"))
}

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name)
}

fn hash_dir(dir: &Path) -> Vec<(PathBuf, u128)> {
    let mut out = Vec::new();
    fn walk(dir: &Path, out: &mut Vec<(PathBuf, u128)>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                walk(&p, out);
            } else if let Ok(bytes) = std::fs::read(&p) {
                let mut h: u128 = 0xcbf29ce484222325;
                for b in bytes {
                    h ^= b as u128;
                    h = h.wrapping_mul(0x100000001b3);
                }
                out.push((p, h));
            }
        }
    }
    walk(dir, &mut out);
    out.sort();
    out
}

/// Run f with a fresh empty temp dir (no fixture copy).
fn with_tmp(f: impl FnOnce(&Path)) {
    use std::sync::atomic::{AtomicUsize, Ordering};
    static SEQ: AtomicUsize = AtomicUsize::new(0);
    let seq = SEQ.fetch_add(1, Ordering::Relaxed);
    let tmp = std::env::temp_dir().join(format!("bbb-report-{}-{seq}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).unwrap();
    f(&tmp);
    let _ = std::fs::remove_dir_all(&tmp);
}

/// Run init in a COPY of the fixture (never mutate the committed one).
/// Includes a per-call counter so parallel tests never share a temp dir.
fn with_copy(fixture_name: &str, f: impl FnOnce(&Path)) {
    use std::sync::atomic::{AtomicUsize, Ordering};
    static SEQ: AtomicUsize = AtomicUsize::new(0);
    let seq = SEQ.fetch_add(1, Ordering::Relaxed);
    let src = fixture(fixture_name);
    let tmp =
        std::env::temp_dir().join(format!("z10-{}-{}-{seq}", fixture_name, std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    copy_dir(&src, &tmp);
    f(&tmp);
    let _ = std::fs::remove_dir_all(&tmp);
}

fn copy_dir(src: &Path, dst: &Path) {
    std::fs::create_dir_all(dst).unwrap();
    for e in std::fs::read_dir(src).unwrap().flatten() {
        let p = e.path();
        let q = dst.join(e.file_name());
        if p.is_dir() {
            copy_dir(&p, &q);
        } else {
            std::fs::copy(&p, &q).unwrap();
        }
    }
}

/// Fix (1): idiomatic lib+bin — snapshot the generated file.
#[test]
fn init_snapshot_lib_bin() {
    with_copy("simple_game", |tmp| {
        let out = Command::new(cli_bin())
            .arg("init")
            .arg("--package")
            .arg("simple_game")
            .current_dir(tmp)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "stderr: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        let generated = std::fs::read_to_string(tmp.join("tests/swarm.rs")).unwrap();
        let expected = "//! Generated by `cargo swarm init`. Safe to edit.\n\
            #[test]\n\
            fn swarm_autotest() {\n\
            \x20   let report = bevy_swarm::autotest::autotest_factory(\n\
            \x20       || simple_game::GamePlugin,\n\
            \x20       bevy_swarm::autotest::AutotestConfig::default(),\n\
            \x20   )\n\
            \x20   .expect(\"autotest\");\n\
            \x20   assert!(report.passed(), \"{}\", report.summary());\n\
            }\n";
        assert_eq!(generated, expected, "snapshot mismatch:\n{generated}");
    });
}

