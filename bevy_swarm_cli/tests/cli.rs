/// Acceptance 2: init without --yes leaves src/ byte-identical.
#[test]
fn init_does_not_touch_src() {
    with_copy("simple_game", |tmp| {
        let before = hash_dir(&tmp.join("src"));
        let out = Command::new(cli_bin())
            .arg("init")
            .arg("--package")
            .arg("simple_game")
            .current_dir(tmp)
            .output()
            .unwrap();
        assert!(out.status.success());
        let after = hash_dir(&tmp.join("src"));
        assert_eq!(before, after, "init modified src/");
    });
}

/// Acceptance 2b: second init without --yes does not overwrite the file.
#[test]
fn init_without_yes_preserves_existing_file() {
    with_copy("simple_game", |tmp| {
        Command::new(cli_bin())
            .arg("init")
            .arg("--package")
            .arg("simple_game")
            .current_dir(tmp)
            .output()
            .unwrap();
        std::fs::write(tmp.join("tests/swarm.rs"), "// custom edits").unwrap();
        Command::new(cli_bin())
            .arg("init")
            .arg("--package")
            .arg("simple_game")
            .current_dir(tmp)
            .output()
            .unwrap();
        let content = std::fs::read_to_string(tmp.join("tests/swarm.rs")).unwrap();
        assert_eq!(content, "// custom edits");
        // With --yes it regenerates.
        Command::new(cli_bin())
            .arg("init")
            .arg("--yes")
            .arg("--package")
            .arg("simple_game")
            .current_dir(tmp)
            .output()
            .unwrap();
        let content = std::fs::read_to_string(tmp.join("tests/swarm.rs")).unwrap();
        assert!(content.contains("bevy_swarm::autotest::autotest_factory("));
    });
}

/// Acceptance 3: full init && run flow on fixture (1) writes
/// target/bevy_swarm/runs/.../report.json and exits 0.
#[test]
#[ignore = "slow: builds the fixture workspace with bevy (network + compile time)"]
fn init_and_run_flow() {
    with_copy("simple_game", |tmp| {
        let init = Command::new(cli_bin())
            .arg("init")
            .arg("--package")
            .arg("simple_game")
            .current_dir(tmp)
            .output()
            .unwrap();
        assert!(init.status.success());

        // Add bevy_swarm via path (published version not available yet).
        let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
        // CARGO_MANIFEST_DIR = <repo>/bevy_swarm_cli; bevy_swarm is ..
        let swarm_path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .canonicalize()
            .unwrap();
        let add = Command::new(&cargo)
            .args(["add", "--dev", "--path"])
            .arg(&swarm_path)
            .current_dir(tmp)
            .output()
            .unwrap();
        assert!(
            add.status.success(),
            "{}",
            String::from_utf8_lossy(&add.stderr)
        );

        let run = Command::new(&cargo)
            .args(["test", "--test", "swarm", "--", "--nocapture"])
            .env("BEVY_SWARM_SEEDS", "2")
            .env("BEVY_SWARM_DURATION", "1")
            .current_dir(tmp)
            .output()
            .unwrap();
        assert!(
            run.status.success(),
            "stdout: {}\nstderr: {}",
            String::from_utf8_lossy(&run.stdout),
            String::from_utf8_lossy(&run.stderr)
        );

        // last pointer exists and points at a report.
        let last = tmp.join("target/bevy_swarm/runs/last");
        assert!(last.exists(), "no last pointer written");
        let dir = std::fs::read_to_string(&last).unwrap();
        let report = tmp
            .join("target/bevy_swarm/runs")
            .join(dir.trim())
            .join("report.json");
        assert!(report.exists(), "no report at {}", report.display());
    });
}

/// swarm-bbb: `cargo swarm report` must surface scope.inactive entries
/// (family + reason) and warnings — golden test with a synthetic report.
#[test]
fn report_prints_inactive_scope_and_warnings() {
    with_tmp(|tmp| {
        let runs = tmp.join("target/bevy_swarm/runs");
        std::fs::create_dir_all(runs.join("golden")).unwrap();
        let report = serde_json::json!({
            "status": "fail",
            "contract_tier": "zero",
            "harness_mode": "in_process",
            "scope": {
                "seeds_run": 2,
                "total_duration_s": 10.0,
                "inactive": [
                    ["semantic_invariants", "no TestApi/Resolver in world: add bevy_swarm as a dev-dependency"],
                    ["intent_effect", "no gameplay state to observe"]
                ]
            },
            "warnings": ["stderr: thread 'main' panicked at src/foo.rs:3:5"],
            "failures": [],
            "runs": []
        });
        std::fs::write(
            runs.join("golden/report.json"),
            serde_json::to_string_pretty(&report).unwrap(),
        )
        .unwrap();
        std::fs::write(runs.join("last"), "golden").unwrap();

        let out = Command::new(cli_bin())
            .arg("report")
            .current_dir(tmp)
            .output()
            .unwrap();
        assert!(out.status.success());
        let stdout = String::from_utf8_lossy(&out.stdout);
        assert!(stdout.contains("inactive checks (2)"), "stdout: {stdout}");
        assert!(
            stdout.contains("[semantic_invariants] no TestApi/Resolver"),
            "stdout: {stdout}"
        );
        assert!(
            stdout.contains("[intent_effect] no gameplay state"),
            "stdout: {stdout}"
        );
        assert!(stdout.contains("warnings (1)"), "stdout: {stdout}");
        assert!(
            stdout.contains("thread 'main' panicked"),
            "stdout: {stdout}"
        );
    });
}

/// swarm-bbb: no regression — reports WITHOUT inactive entries and
/// warnings render exactly as before (no new sections).
#[test]
fn report_no_sections_when_absent() {
    with_tmp(|tmp| {
        let runs = tmp.join("target/bevy_swarm/runs");
        std::fs::create_dir_all(runs.join("plain")).unwrap();
        let report = serde_json::json!({
            "status": "pass",
            "contract_tier": "zero",
            "harness_mode": "in_process",
            "scope": { "seeds_run": 1, "total_duration_s": 1.0 },
            "failures": [],
            "runs": []
        });
        std::fs::write(
            runs.join("plain/report.json"),
            serde_json::to_string_pretty(&report).unwrap(),
        )
        .unwrap();
        std::fs::write(runs.join("last"), "plain").unwrap();

        let out = Command::new(cli_bin())
            .arg("report")
            .current_dir(tmp)
            .output()
            .unwrap();
        assert!(out.status.success());
        let stdout = String::from_utf8_lossy(&out.stdout);
        assert!(!stdout.contains("inactive checks"), "stdout: {stdout}");
        assert!(!stdout.contains("warnings"), "stdout: {stdout}");
    });
}
