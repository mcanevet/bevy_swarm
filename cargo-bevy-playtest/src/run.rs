//! `cargo bevy-playtest run`: run the generated tests with env overrides, and
//! X1 CLI mode (run a plugin from outside the game crate via a
//! generated runner under special_build_root()).

use std::path::{Path, PathBuf};
use std::process::Command;

/// Install bevy_playtest as a dev-dependency of the game crate if absent.
#[allow(dead_code)]
pub fn ensure_dev_dependency(manifest_path: Option<&Path>) -> Result<(), String> {
    let mut cmd = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.args(["add", "--dev", "bevy_playtest"]);
    if let Some(m) = manifest_path {
        cmd.arg("--manifest-path").arg(m);
    }
    let out = cmd
        .output()
        .map_err(|e| format!("cargo add failed to start: {e}"))?;
    // cargo add is idempotent-safe: adding twice upgrades/keeps.
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).into());
    }
    Ok(())
}

pub struct RunOptions {
    pub manifest_path: Option<PathBuf>,
    pub package: Option<String>,
    pub seeds: Option<u64>,
    pub duration: Option<f32>,
    pub report_json: Option<PathBuf>,
    /// X1 CLI mode: run the plugin from outside the game crate.
    pub plugin: Option<String>,
}

/// Plain mode: cargo test --test swarm with env overrides autotest() reads.
pub fn run(opts: &RunOptions) -> Result<i32, String> {
    let mut cmd = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.args(["test", "--test", "swarm", "--", "--nocapture"]);
    if let Some(m) = &opts.manifest_path {
        cmd.arg("--manifest-path").arg(m);
    }
    if let Some(p) = &opts.package {
        cmd.args(["--package", p]);
    }
    if let Some(s) = opts.seeds {
        cmd.env("BEVY_PLAYTEST_SEEDS", s.to_string());
    }
    if let Some(d) = opts.duration {
        cmd.env("BEVY_PLAYTEST_DURATION", d.to_string());
    }
    let status = cmd
        .status()
        .map_err(|e| format!("cargo test failed to start: {e}"))?;
    Ok(status.code().unwrap_or(1))
}

/// X1 CLI mode: generate a runner crate under special_build_root() that
/// depends on the game crate + bevy_playtest, then `cargo test` it. The
/// game crate's dev-deps are never touched.
pub fn run_external(opts: &RunOptions) -> Result<i32, String> {
    let Some(plugin) = &opts.plugin else {
        return Err("--plugin <path> is required for external runner mode".into());
    };
    let manifest = opts
        .manifest_path
        .clone()
        .unwrap_or_else(|| PathBuf::from("Cargo.toml"));
    let root = Path::new(&manifest)
        .parent()
        .unwrap_or(Path::new("."))
        .canonicalize()
        .map_err(|e| e.to_string())?;

    let build_root = bevy_playtest::conventions::special_build_root().join("cli-runner");
    std::fs::create_dir_all(&build_root).map_err(|e| e.to_string())?;

    // Minimal manifest referencing the game crate by absolute path.
    let game_manifest = root.join("Cargo.toml");
    // The game's real package name is read from cargo metadata at
    // generation time.
    let name = game_package_name(&game_manifest)?;
    let bevy_playtest_path = find_bevy_playtest_path()?;
    let runner_toml = format!(
        "[package]\n\
         name = \"bevy_playtest_cli_runner\"\n\
         version = \"0.0.0\"\n\
         edition = \"2021\"\n\
         publish = false\n\n\
         [dependencies]\n\
         bevy_playtest = {{ path = {bevy_playtest_path:?} }}\n\
         game = {{ package = \"{name}\", path = {:?} }}\n",
        root
    );
    std::fs::write(build_root.join("Cargo.toml"), runner_toml).map_err(|e| e.to_string())?;

    let test_src = format!(
        "//! Generated by cargo bevy-playtest run --plugin. Do not edit.\n\
         #[test]\n\
         fn swarm_autotest() {{\n\
         \x20   let report = bevy_playtest::autotest::autotest(\n\
         \x20       game::{plugin},\n\
         \x20       bevy_playtest::autotest::AutotestConfig::default(),\n\
         \x20   )\n\
         \x20   .expect(\"autotest\");\n\
         \x20   assert!(report.passed(), \"{{}}\", report.summary());\n\
         }}\n"
    );
    std::fs::write(build_root.join("swarm.rs"), test_src).map_err(|e| e.to_string())?;

    let mut cmd = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.args(["test", "--manifest-path"])
        .arg(build_root.join("Cargo.toml"));
    if let Some(s) = opts.seeds {
        cmd.env("BEVY_PLAYTEST_SEEDS", s.to_string());
    }
    if let Some(d) = opts.duration {
        cmd.env("BEVY_PLAYTEST_DURATION", d.to_string());
    }
    let status = cmd
        .status()
        .map_err(|e| format!("cargo test failed to start: {e}"))?;
    Ok(status.code().unwrap_or(1))
}

fn game_package_name(game_manifest: &Path) -> Result<String, String> {
    let out = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .args([
            "metadata",
            "--no-deps",
            "--format-version",
            "1",
            "--manifest-path",
        ])
        .arg(game_manifest)
        .output()
        .map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).into());
    }
    let v: serde_json::Value = serde_json::from_slice(&out.stdout).map_err(|e| e.to_string())?;
    let name = v["packages"][0]["name"]
        .as_str()
        .ok_or("no package in metadata")?;
    Ok(name.to_string())
}

fn find_bevy_playtest_path() -> Result<PathBuf, String> {
    // The CLI lives in bevy_playtest_cli/ within the bevy_playtest repo;
    // from a published binary this would resolve differently, but
    // for --path installs (documented) the sibling works.
    let candidates = [
        std::env::var("BEVY_PLAYTEST_CRATE_PATH")
            .ok()
            .map(PathBuf::from),
        Some(PathBuf::from("../../..")), // fallback relative
    ];
    for c in candidates.into_iter().flatten() {
        if c.join("Cargo.toml").exists() {
            let canonical = c.canonicalize().map_err(|e| e.to_string())?;
            if std::fs::read_to_string(canonical.join("Cargo.toml"))
                .map(|s| s.contains("name = \"bevy_playtest\""))
                .unwrap_or(false)
            {
                return Ok(canonical);
            }
        }
    }
    Err(
        "cannot locate the bevy_playtest crate for the runner — set \
         BEVY_PLAYTEST_CRATE_PATH to the bevy_playtest checkout"
            .into(),
    )
}
